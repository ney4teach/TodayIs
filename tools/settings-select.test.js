document.querySelector('#dialog').showModal();
document.querySelector('#run-spring-test').onclick = async () => {
  const output = document.querySelector('#spring-test-result');
  output.textContent = '';
  const assert = (condition, message) => {if (!condition) throw new Error(message)};
  const frame = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
  const reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;
  try {
    const source = document.querySelector('#settings-engine');
    source.value = 'Google';source.dispatchEvent(new Event('change', {bubbles:true}));
    const trigger = source.parentElement.querySelector('.settings-select-trigger');
    assert(trigger, 'Нет меню с JavaScript-пружиной');
    let changes = 0;
    source.addEventListener('change', () => changes++, {once:true});
    trigger.click();await frame();
    const menu = document.getElementById(trigger.getAttribute('aria-controls'));
    assert(menu.matches(':popover-open'), 'Меню не открылось');
    assert(reduce ? !menu.getAnimations().length : menu.getAnimations().some(a => a.effect.getKeyframes().length === 31), 'Неверная анимация открытия');
    const rows = [...menu.querySelectorAll('[role=option]')];
    rows[2].dispatchEvent(new PointerEvent('pointerenter'));await frame();
    const highlight = menu.querySelector('.settings-select-highlight');
    assert(reduce ? !highlight.getAnimations().length : highlight.getAnimations().some(a => a.effect.getKeyframes().length === 31), 'Неверная пружина выделения');
    rows[2].click();await frame();
    assert(source.value === 'DuckDuckGo' && changes === 1, 'Не сработало событие исходного select');
    assert(!menu.matches(':popover-open') && document.activeElement === trigger, 'Не закрыто меню или потерян фокус');
    source.value = 'Google';source.dispatchEvent(new Event('change', {bubbles:true}));
    assert(trigger.textContent.includes('Google'), 'Не обновилось программно выбранное значение');
    source.focus();assert(document.activeElement === trigger, 'Поиск настроек не может сфокусировать меню');
    trigger.click();await frame();
    document.activeElement.dispatchEvent(new KeyboardEvent('keydown', {key:'End',bubbles:true}));
    assert(document.activeElement.textContent.includes('DuckDuckGo'), 'Не работает End');
    document.activeElement.dispatchEvent(new KeyboardEvent('keydown', {key:'я',bubbles:true}));
    assert(document.activeElement.textContent.includes('Яндекс'), 'Не работает поиск по буквам');
    document.activeElement.dispatchEvent(new KeyboardEvent('keydown', {key:'Escape',bubbles:true}));
    assert(!menu.matches(':popover-open'), 'Escape не закрывает меню');
    source.disabled = true;await frame();assert(trigger.disabled, 'Не учтено disabled');
    source.disabled = false;await frame();
    const shifts = document.querySelector('#shift-kind');
    shifts.parentElement.querySelector('button').click();await frame();
    const shiftMenu = document.querySelector('.settings-select-menu:popover-open');
    assert(shiftMenu.querySelectorAll('[role=option]').length === 2, 'Показаны скрытые или недоступные варианты');
    shiftMenu.hidePopover();
    const holder = source.closest('label');holder.remove();await frame();
    assert(!menu.isConnected, 'Меню осталось после смены страницы настроек');
    document.querySelector('#fields').prepend(holder);await frame();
    assert(source.parentElement.querySelector('.settings-select-trigger'), 'Меню не восстановилось');
    output.textContent = 'PASS: пружины, выбор, события, клавиатура, disabled, обновление и очистка';
  } catch (error) {output.textContent = 'FAIL: ' + error.message}
};
